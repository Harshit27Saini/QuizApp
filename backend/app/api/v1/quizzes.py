from typing import List, Dict, Any
from fastapi import APIRouter, Depends, status
from app.core.security import get_current_user
from app.core.database import db
from app.core.errors import not_found_error, bad_request_error
from app.services.quiz_engine.generator import generate_quiz_questions
from app.schemas.quiz import QuizGenerateRequest, QuizResponse, QuestionPublic

router = APIRouter(prefix="/quizzes", tags=["Quizzes & Generation"])


@router.post("/generate", response_model=QuizResponse, status_code=status.HTTP_201_CREATED)
async def generate_quiz(
    payload: QuizGenerateRequest,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """
    Generates an active-recall quiz grounded in one or more uploaded documents.
    Supports STRICT and CONCEPTUAL modes with MCQ and MSQ question types.
    """
    # 1. Gather all sections from the specified documents
    all_sections = []
    doc_titles = []
    for doc_id in payload.document_ids:
        doc = await db.get_document(doc_id, current_user["id"])
        if not doc:
            raise not_found_error("Document", doc_id)
        doc_titles.append(doc["filename"])
        sections = await db.get_document_sections(doc_id)
        all_sections.extend(sections)

    if not all_sections:
        raise bad_request_error("Selected document(s) have no parsed text sections available.")

    # 2. Generate questions via AI engine
    raw_questions = await generate_quiz_questions(
        sections=all_sections,
        mode=payload.mode,
        difficulty=payload.difficulty,
        count=payload.question_count,
        allowed_types=payload.question_types
    )

    # 3. Create Quiz record
    title = payload.title or f"{payload.mode.capitalize()} Quiz: {', '.join(doc_titles[:2])}"
    quiz_record = await db.create_quiz(
        user_id=current_user["id"],
        collection_id=payload.collection_id,
        title=title,
        mode=payload.mode,
        difficulty=payload.difficulty,
        document_ids=payload.document_ids
    )

    # 4. Associate and persist generated questions
    question_payloads = [
        {
            **q,
            "quiz_id": quiz_record["id"],
            "source_document_id": payload.document_ids[0]
        }
        for q in raw_questions
    ]
    created_questions = await db.create_questions(question_payloads)

    # 5. Sanitize public questions (never leak answers or explanations to the taker)
    public_questions = [
        QuestionPublic(
            id=q["id"],
            quiz_id=q["quiz_id"],
            question_type=q["question_type"],
            prompt=q["prompt"],
            options=q["options"],
            difficulty=q["difficulty"],
            source_page=q.get("source_page")
        )
        for q in created_questions
    ]

    return {
        **quiz_record,
        "questions": public_questions
    }


@router.get("/{quiz_id}", response_model=QuizResponse)
async def get_quiz(
    quiz_id: str,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Retrieves an existing quiz and its active questions (sanitized for test-taking)."""
    quiz = await db.get_quiz(quiz_id, current_user["id"])
    if not quiz:
        raise not_found_error("Quiz", quiz_id)

    questions = await db.get_quiz_questions(quiz_id)
    public_questions = [
        QuestionPublic(
            id=q["id"],
            quiz_id=q["quiz_id"],
            question_type=q["question_type"],
            prompt=q["prompt"],
            options=q["options"],
            difficulty=q["difficulty"],
            source_page=q.get("source_page")
        )
        for q in questions
    ]

    return {
        **quiz,
        "questions": public_questions
    }


@router.get("", response_model=List[QuizResponse])
async def list_quizzes(current_user: Dict[str, Any] = Depends(get_current_user)):
    """Lists all quizzes generated by the user."""
    return await db.list_quizzes(user_id=current_user["id"])

